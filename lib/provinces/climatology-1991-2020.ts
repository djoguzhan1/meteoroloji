void TR_PLATE_NUMBERS;

function interpolateCyclicMonthly(monthly: MonthlyTuple12, dayOfYear: number): number {
  const safeDoy = Number.isFinite(dayOfYear) ? Math.round(dayOfYear) : 180;
  const wrappedDoy = ((((safeDoy - 1) % 365) + 365) % 365) + 1;

  let hiIdx = 0;
  while (hiIdx < 12 && MID_MONTH_DOY[hiIdx] < wrappedDoy) {
    hiIdx++;
  }
  const idxB = hiIdx % 12;
  const idxA = (idxB + 11) % 12;

  const doyA = MID_MONTH_DOY[idxA];
  let doyB = MID_MONTH_DOY[idxB];
  let probe = wrappedDoy;
  if (doyB <= doyA) {
    doyB += 365;
    if (probe < doyA) probe += 365;
  }

  const linFrac = clamp((probe - doyA) / Math.max(1, doyB - doyA), 0, 1);
  // C1-smooth cosine interpolation across mid-month anchors
  const cosFrac = 0.5 * (1 - Math.cos(Math.PI * linFrac));
  return monthly[idxA] * (1 - cosFrac) + monthly[idxB] * cosFrac;
}

/**
 * 81 İl 1991–2020 WMO/MGM normallerinden C¹ kosinüs aylık enterpolasyon + mevsimsel
 * lapse-rate taşımasıyla herhangi bir gün (`dayOfYear: 1..366`) ve rakım için günlük normal üretir.
 * `TR-16` Bursa için `lib/extended-horizon.ts` WMO 17116 lapse-rate denklemini birebir korur.
 */
export function computeTrDailyClimatologyNormal(params: {
  provinceCode: TrProvinceCode;
  lat: number;
  lon: number;
  elevationM: number;
  dayOfYear: number;
}): TrDailyClimatologyNormal {
  const rec =
    TR81_CLIMATOLOGY_1991_2020[params.provinceCode] ??
    TR81_CLIMATOLOGY_1991_2020["TR-16"];

  const elevM = Number.isFinite(params.elevationM)
    ? Math.max(-50, params.elevationM)
    : rec.referenceElevationM;
  const safeDoy = Number.isFinite(params.dayOfYear) ? params.dayOfYear : 180;

  const baseMax = interpolateCyclicMonthly(rec.tmaxC, safeDoy);
  const baseMin = interpolateCyclicMonthly(rec.tminC, safeDoy);

  const dailyPrecipRates = rec.precipMm.map(
    (mm, mIdx) => mm / MONTH_DAYS[mIdx]
  ) as unknown as MonthlyTuple12;
  const dailyWetPctRates = rec.wetDays.map((wd, mIdx) =>
    clamp((wd / MONTH_DAYS[mIdx]) * 100, 0.5, 96)
  ) as unknown as MonthlyTuple12;

  const baseDailyPrecipMm = Math.max(0, interpolateCyclicMonthly(dailyPrecipRates, safeDoy));
  const baseWetProbPct = clamp(interpolateCyclicMonthly(dailyWetPctRates, safeDoy), 0.5, 96);

  const dzKm = (elevM - rec.referenceElevationM) / 1000;

  let tmaxNormalC: number;
  let tminNormalC: number;

  if (params.provinceCode === "TR-16") {
    // Exact parity with `lib/extended-horizon.ts` WMO 17116 Bursa (100 m) equations
    tmaxNormalC = Number((baseMax - 6.0 * dzKm).toFixed(1));
    tminNormalC = Number((baseMin - 5.1 * dzKm).toFixed(1));
  } else {
    // Seasonal lapse-rate: steeper convective mixing in summer, shallower cold-pool gradient in winter
    const summerWave = Math.cos(((2 * Math.PI) / 365.25) * (safeDoy - 196));
    const lapseMaxPerKm = 6.1 + 0.5 * summerWave; // 5.6 winter .. 6.6 summer
    const lapseMinPerKm = 4.9 + 0.5 * summerWave; // 4.4 winter .. 5.4 summer

    const rawMax = baseMax - lapseMaxPerKm * dzKm;
    const rawMin = baseMin - lapseMinPerKm * dzKm;

    tmaxNormalC = Number(rawMax.toFixed(1));
    tminNormalC = Number(Math.min(tmaxNormalC - 2.0, rawMin).toFixed(1));
  }

  if (tminNormalC >= tmaxNormalC) {
    tminNormalC = Number((tmaxNormalC - 2.0).toFixed(1));
  }

  // Orographic precipitation scaling with altitude relative to province reference station
  const oroPrecipScale = clamp(1 + 0.22 * dzKm, 0.65, 1.65);
  const oroWetProbScale = clamp(1 + 0.08 * dzKm, 0.82, 1.24);

  const dailyPrecipNormalMm = Number(
    Math.max(0, baseDailyPrecipMm * oroPrecipScale).toFixed(2)
  );
  const wetDayProbPct = Number(
    clamp(baseWetProbPct * oroWetProbScale, 0.5, 96).toFixed(1)
  );

  return {
    tmaxNormalC,
    tminNormalC,
    dailyPrecipNormalMm,
    wetDayProbPct
  };
}
