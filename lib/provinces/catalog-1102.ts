/**
 * Folds Turkish diacritics (`İ/I/ı/ş/ğ/ü/ö/ç/â/î/û` and decomposed NFD marks) into lowercase ASCII
 * search tokens separated by single spaces.
 */
export function foldTrCatalog(value: string): string {
  if (!value) return "";
  return value
    .normalize("NFC")
    .replace(/İ/g, "i")
    .replace(/I/g, "i")
    .replace(/ı/g, "i")
    .replace(/Ş/g, "s")
    .replace(/ş/g, "s")
    .replace(/Ğ/g, "g")
    .replace(/ğ/g, "g")
    .replace(/Ü/g, "u")
    .replace(/ü/g, "u")
    .replace(/Ö/g, "o")
    .replace(/ö/g, "o")
    .replace(/Ç/g, "c")
    .replace(/ç/g, "c")
    .replace(/[Ââ]/g, "a")
    .replace(/[Îî]/g, "i")
    .replace(/[Ûû]/g, "u")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function padPlate(plate: number): string {
  return plate < 10 ? `0${plate}` : String(plate);
}

