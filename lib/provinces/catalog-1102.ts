/**
 * Ultra-fast (< 0.3 ms) Turkish-folded national catalog search supporting:
 * - Single & homonymous district queries (`"Ereğli"`, `"Kemer"`, `"Edremit"`, `"Gölbaşı"`, `"Yenice"`, `"Yenişehir"`, `"Kartepe"`)
 * - Compound province/plate + district/ski queries (`"konya ereğli"`, `"67 ereğli"`, `"kartepe kayak"`, `"rize çamlıhemşin"`)
 * - Optional `provinceHint` ranking boost and `kinds` filter.
 */
export function searchTrNationalCatalog(
  query: string,
  opts?: SearchTrCatalogOptions
): CatalogLocationEntry[] {
  const limit = Math.max(1, opts?.limit ?? 15);
  const provinceHint = opts?.provinceHint ?? null;
  const kindFilter = opts?.kinds && opts.kinds.length > 0 ? new Set(opts.kinds) : null;

  const foldedQuery = foldTrCatalog(query);
  if (!foldedQuery) {
    if (provinceHint) {
      const provItems = BY_PROVINCE_MAP.get(provinceHint) ?? [];
      const filtered = kindFilter ? provItems.filter((e) => kindFilter.has(e.kind)) : provItems;
      return filtered.slice(0, limit);
    }
    const out: CatalogLocationEntry[] = [];
    for (let i = 0; i < INDEXED_ROWS.length && out.length < limit; i++) {
      const e = INDEXED_ROWS[i].entry;
      if (kindFilter && !kindFilter.has(e.kind)) continue;
      if (e.kind === "province_center" || kindFilter) {
        out.push(e);
      }
    }
    return out;
  }

  const tokens = foldedQuery.split(" ").filter(Boolean);
  const tokenCount = tokens.length;

  const matchedEntries: CatalogLocationEntry[] = [];
  const matchedScores: number[] = [];

  for (let i = 0; i < INDEXED_ROWS.length; i++) {
    const row = INDEXED_ROWS[i];
    const entry = row.entry;
    if (kindFilter && !kindFilter.has(entry.kind)) continue;

    // Every query token must match at least one indexed field/substring
    let allTokensMatched = true;
    let tokenScoreSum = 0;
    let matchedProvOrPlateToken = false;
    let matchedNameOrAliasToken = false;

    for (let tIdx = 0; tIdx < tokenCount; tIdx++) {
      const tok = tokens[tIdx];
      const isNumericTok = tok.charCodeAt(0) >= 48 && tok.charCodeAt(0) <= 57;

      if (isNumericTok) {
        if (tok === row.platePadded || tok === row.plateRaw) {
          tokenScoreSum += 220;
          matchedProvOrPlateToken = true;
          continue;
        }
        if (
          entry.wmoId === tok ||
          String(entry.mgmSondurumIstNo ?? "") === tok ||
          String(entry.mgmMerkezId ?? "") === tok
        ) {
          tokenScoreSum += 200;
          matchedNameOrAliasToken = true;
          continue;
        }
        allTokensMatched = false;
        break;
      }

      if (tok === row.foldedName) {
        tokenScoreSum += 320;
        matchedNameOrAliasToken = true;
        continue;
      }

      // Check exact word in nameWords
      let wordExact = false;
      let wordPrefix = false;
      for (let w = 0; w < row.nameWords.length; w++) {
        const nw = row.nameWords[w];
        if (nw === tok) {
          wordExact = true;
          break;
        }
        if (nw.startsWith(tok)) {
          wordPrefix = true;
        }
      }
      if (wordExact) {
        tokenScoreSum += 250;
        matchedNameOrAliasToken = true;
        continue;
      }

      if (tok === row.foldedProv || tok === row.foldedProvCode) {
        tokenScoreSum += 210;
        matchedProvOrPlateToken = true;
        continue;
      }

      // Check aliases exact / prefix
      let aliasExact = false;
      let aliasSub = false;
      for (let a = 0; a < row.aliasFoldedList.length; a++) {
        const al = row.aliasFoldedList[a];
        if (al === tok) {
          aliasExact = true;
          break;
        }
        if (al.includes(tok)) {
          aliasSub = true;
        }
      }
      if (aliasExact) {
        tokenScoreSum += 240;
        matchedNameOrAliasToken = true;
        continue;
      }

      if (wordPrefix || row.foldedName.startsWith(tok)) {
        tokenScoreSum += 180;
        matchedNameOrAliasToken = true;
        continue;
      }

      if (row.foldedProv.startsWith(tok)) {
        tokenScoreSum += 140;
        matchedProvOrPlateToken = true;
        continue;
      }

      if (aliasSub) {
        tokenScoreSum += 155;
        matchedNameOrAliasToken = true;
        continue;
      }

      if (row.foldedName.includes(tok)) {
        tokenScoreSum += 120;
        matchedNameOrAliasToken = true;
        continue;
      }

      if (row.searchBlob.includes(tok)) {
        tokenScoreSum += 95;
        continue;
      }

      allTokensMatched = false;
      break;
    }

    if (!allTokensMatched) continue;

    let score = tokenScoreSum;

    // Whole-phrase bonuses
    if (foldedQuery === row.foldedName) {
      score += entry.kind === "province_center" ? 500 : 420;
    } else if (foldedQuery === `${row.foldedProv} ${row.foldedName}` || foldedQuery === `${row.platePadded} ${row.foldedName}`) {
      score += 520;
    } else if (foldedQuery === row.foldedId || foldedQuery === row.foldedSlug) {
      score += 480;
    }

    // Compound query synergy (e.g. "konya eregli", "67 eregli", "rize camlihemsin")
    if (tokenCount >= 2 && matchedProvOrPlateToken && matchedNameOrAliasToken) {
      score += 260;
    }

    // Kind tie-breaking
    if (entry.kind === "province_center") {
      // Only boost province_center if query didn't specifically ask for another district/ski
      if (tokenCount === 1 && (foldedQuery === row.foldedProv || row.foldedProv.startsWith(foldedQuery))) {
        score += 180;
      } else {
        score += 20;
      }
    } else if (entry.kind === "summit_ski") {
      if (
        foldedQuery.includes("kayak") ||
        foldedQuery.includes("zirve") ||
        foldedQuery.includes("dag")
      ) {
        score += 240;
      } else {
        score += 12;
      }
    } else if (entry.kind === "district") {
      score += 15;
    }

    // Penalize generic "<Province> Merkez" districts slightly against exact province_center or named districts
    if (entry.slug === "merkez" && !foldedQuery.includes("merkez")) {
      score -= 60;
    }

    if (provinceHint && entry.provinceCode === provinceHint) {
      score += 160;
    }

    matchedEntries.push(entry);
    matchedScores.push(score);
  }

  // Sort indices by score descending, then kind priority, then plateNumber
  const indices = Array.from({ length: matchedEntries.length }, (_, idx) => idx);
  indices.sort((a, b) => {
    const diff = matchedScores[b] - matchedScores[a];
    if (diff !== 0) return diff;
    return matchedEntries[a].plateNumber - matchedEntries[b].plateNumber;
  });

  const resultCount = Math.min(limit, indices.length);
  const results: CatalogLocationEntry[] = new Array(resultCount);
  for (let k = 0; k < resultCount; k++) {
    results[k] = matchedEntries[indices[k]];
  }
  return results;
}

function haversineDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const toRad = Math.PI / 180;
  const dLat = (lat2 - lat1) * toRad;
  const dLon = (lon2 - lon1) * toRad;
  const sinLat = Math.sin(dLat * 0.5);
  const sinLon = Math.sin(dLon * 0.5);
  const a =
    sinLat * sinLat +
    Math.cos(lat1 * toRad) * Math.cos(lat2 * toRad) * sinLon * sinLon;
  return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export interface NearestCatalogOptions {
  provinceCode?: TrProvinceCode | null;
  maxDistKm?: number;
  kinds?: readonly CatalogLocationEntry["kind"][];
}

/**
 * Finds the nearest `CatalogLocationEntry` to `(lat, lon)`, optionally constrained to a specific
 * `provinceCode` and `maxDistKm` radius.
 */
export function findNearestTrCatalogEntry(
  lat: number,
  lon: number,
  provinceCodeOrOpts?: TrProvinceCode | null | NearestCatalogOptions,
  maxDistKm: number = Infinity
): CatalogLocationEntry | null {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;

  let targetProvince: TrProvinceCode | null = null;
  let effectiveMaxKm = maxDistKm;
  let kindFilter: Set<CatalogLocationEntry["kind"]> | null = null;

  if (typeof provinceCodeOrOpts === "string") {
    targetProvince = provinceCodeOrOpts;
  } else if (typeof provinceCodeOrOpts === "object" && provinceCodeOrOpts !== null) {
    targetProvince = provinceCodeOrOpts.provinceCode ?? null;
    if (provinceCodeOrOpts.maxDistKm !== undefined) {
      effectiveMaxKm = provinceCodeOrOpts.maxDistKm;
    }
    if (provinceCodeOrOpts.kinds && provinceCodeOrOpts.kinds.length > 0) {
      kindFilter = new Set(provinceCodeOrOpts.kinds);
    }
  }

  const candidates = targetProvince
    ? (BY_PROVINCE_MAP.get(targetProvince) ?? [])
    : TR_NATIONAL_CATALOG;

  let bestEntry: CatalogLocationEntry | null = null;
  let bestDist = effectiveMaxKm;

  for (let i = 0; i < candidates.length; i++) {
    const c = candidates[i];
    if (kindFilter && !kindFilter.has(c.kind)) continue;
    const d = haversineDistanceKm(lat, lon, c.lat, c.lon);
    if (d <= bestDist) {
      bestDist = d;
      bestEntry = c;
    }
  }

  return bestEntry;
}

