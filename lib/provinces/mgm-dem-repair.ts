export interface ResolveStationElevationOptions {
  rawElevationM?: number | null;
  istNo?: number | null;
  merkezId?: number | null;
  fallbackElevationM?: number;
}

export function resolveVerifiedStationElevationM(options: ResolveStationElevationOptions): number;
export function resolveVerifiedStationElevationM(
  rawElevationM: number | null | undefined,
  istNo?: number | null,
  merkezId?: number | null,
  fallbackElevationM?: number
): number;
export function resolveVerifiedStationElevationM(
  first: ResolveStationElevationOptions | number | null | undefined,
  istNoArg?: number | null,
  merkezIdArg?: number | null,
  fallbackArg?: number
): number {
  let rawElevationM: number | null | undefined;
  let istNo: number | null | undefined;
  let merkezId: number | null | undefined;
  let fallbackElevationM: number | undefined;

  if (typeof first === "object" && first !== null) {
    rawElevationM = first.rawElevationM;
    istNo = first.istNo;
    merkezId = first.merkezId;
    fallbackElevationM = first.fallbackElevationM;
  } else {
    rawElevationM = first;
    istNo = istNoArg;
    merkezId = merkezIdArg;
    fallbackElevationM = fallbackArg;
  }

  const byMerkez =
    merkezId != null && Number.isFinite(merkezId)
      ? MGM_DEM_ELEVATION_REPAIR_BY_MERKEZ_ID[merkezId]
      : undefined;
  const byIst =
    istNo != null && Number.isFinite(istNo)
      ? MGM_DEM_ELEVATION_REPAIR_BY_ISTNO[istNo]
      : undefined;

  if (rawElevationM != null && Number.isFinite(rawElevationM) && rawElevationM > 2) {
    if (rawElevationM <= 10 && byMerkez !== undefined && byMerkez - rawElevationM >= 20) {
      return byMerkez;
    }
    return Math.round(rawElevationM);
  }

  // Missing or <= 2 m raw elevation: apply GLO-90 DEM repair
  if (byIst !== undefined && byMerkez !== undefined) {
    if (byIst <= 10 && byMerkez > 10) {
      return byMerkez;
    }
    return byIst;
  }
  if (byIst !== undefined) {
    return byIst;
  }
  if (byMerkez !== undefined) {
    return byMerkez;
  }

  if (rawElevationM != null && Number.isFinite(rawElevationM) && rawElevationM >= 0) {
    return Math.round(rawElevationM);
  }
  return Math.max(0, Math.round(fallbackElevationM ?? 0));
}

export function isCrossProvinceProxyMerkez(merkezId: number | null | undefined): boolean {
  if (merkezId == null || !Number.isFinite(merkezId)) return false;
  return CROSS_PROVINCE_PROXY_MERKEZ_IDS.has(merkezId);
}

export function resolveMgmStationOwnerProvince(
  istNo: number | null | undefined
): TrProvinceCode | null {
  if (istNo == null || !Number.isFinite(istNo)) return null;
  return STATIC_MGM_ISTNO_OWNER_PROVINCE[istNo] ?? null;
}

export function isMgmStationOwnedByProvince(
  istNo: number | null | undefined,
  expectedProvince: TrProvinceCode
): boolean {
  const owner = resolveMgmStationOwnerProvince(istNo);
  return owner !== null && owner === expectedProvince;
}
