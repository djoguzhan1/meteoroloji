function solarSinElevBursa(doy: number, utcHour: number): number {
  const gamma = (2 * Math.PI * (doy - 1 + (utcHour - 12) / 24)) / 365.25;
  const decl =
    0.006918 -
    0.399912 * Math.cos(gamma) +
    0.070257 * Math.sin(gamma) -
    0.006758 * Math.cos(2 * gamma);
  const eqt =
    229.18 *
    (0.000075 +
      0.001868 * Math.cos(gamma) -
      0.032077 * Math.sin(gamma) -
      0.014615 * Math.cos(2 * gamma) -
      0.040849 * Math.sin(2 * gamma));
  const tst = (((utcHour * 60 + eqt + 4 * 29.0133) % 1440) + 1440) % 1440;
  const ha = ((tst / 4 - 180) * Math.PI) / 180;
  const latR = (40.2308 * Math.PI) / 180;
  return Math.sin(latR) * Math.sin(decl) + Math.cos(latR) * Math.cos(decl) * Math.cos(ha);
}

function medianOfSorted(sorted: number[]): number {
  if (sorted.length === 0) return 0;
  const m = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? 0.5 * (sorted[m - 1] + sorted[m]) : sorted[m];
}

function computeSkillPriorBackbone(vecT: number[], leadDayBucket: number, hasAifs: boolean): number {
  let priors: number[];
  if (leadDayBucket <= 1) {
    priors = hasAifs
      ? [0.24, 0.14, 0.25, 0.11, 0.13, 0.04, 0.05, 0.04]
      : [0.33, 0.0, 0.28, 0.13, 0.14, 0.04, 0.04, 0.04];
  } else if (leadDayBucket <= 3) {
    priors = hasAifs
      ? [0.24, 0.25, 0.18, 0.11, 0.09, 0.04, 0.05, 0.04]
      : [0.40, 0.0, 0.23, 0.14, 0.10, 0.04, 0.05, 0.04];
  } else if (leadDayBucket <= 6) {
    priors = hasAifs
      ? [0.26, 0.35, 0.13, 0.11, 0.05, 0.05, 0.05]
      : [0.48, 0.0, 0.18, 0.15, 0.06, 0.07, 0.06];
  } else {
    priors = hasAifs
      ? [0.28, 0.44, 0.08, 0.10, 0.10]
      : [0.56, 0.0, 0.14, 0.15, 0.15];
  }
  let s = 0;
  let w = 0;
  for (let i = 0; i < Math.min(vecT.length, priors.length); i++) {
    s += vecT[i] * priors[i];
    w += priors[i];
  }
  return w > 0 ? s / w : vecT[0];
}

