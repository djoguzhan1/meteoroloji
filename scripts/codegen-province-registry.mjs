#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const specsDir = path.join(repoRoot, "lib", "provinces", "specs");
const targetFile = path.join(repoRoot, "lib", "provinces", "registry.ts");

const nonBursaPlates = [];
for (let i = 1; i <= 81; i++) {
  if (i === 16) continue;
  const pad = String(i).padStart(2, "0");
  const specPath = path.join(specsDir, `tr-${pad}.ts`);
  if (!fs.existsSync(specPath)) {
    throw new Error(`[ORCH-00] Missing province spec file: ${specPath}`);
  }
  nonBursaPlates.push(pad);
}

const switchCases = nonBursaPlates
  .map(
    (pad) =>
      `    case "TR-${pad}":\n      return (await import("./specs/tr-${pad}")).default;`
  )
  .join("\n");

const content = `/**
 * AUTO-GENERATED BY scripts/codegen-province-registry.mjs (ORCH-00)
 * DO NOT EDIT MANUALLY.
 *
 * Server-side lazy-sharded registry for all 80 non-Bursa provinces (TR-01..TR-81 except TR-16).
 * Bursa (TR-16) returns null here so its cryptographically sealed v5.0 pipeline remains 100% sovereign.
 */

import { loadProvinceCalibrationBundle } from "./emos-weights";
import {
  isTrProvinceCode,
  type ClimateRegionKey,
  type ProvinceCalibrationBundle,
  type ProvinceClientSummary,
  type ProvinceCode,
  type ProvinceSpec,
  type TrProvinceCode
} from "./types";

const specPromiseCache = new Map<TrProvinceCode, Promise<ProvinceSpec>>();

async function importProvinceSpecRaw(code: TrProvinceCode): Promise<ProvinceSpec | null> {
  switch (code) {
    case "TR-16":
      return null;
${switchCases}
    default:
      return null;
  }
}

/**
 * Lazily loads and freezes the bespoke microclimate specification for a Turkish province.
 * Returns \`null\` for \`TR-16\` (sovereign Bursa engine) and \`GLOBAL\` coordinates.
 */
export async function loadProvinceSpec(
  provinceCode: ProvinceCode | string | null | undefined
): Promise<ProvinceSpec | null> {
  if (!isTrProvinceCode(provinceCode) || provinceCode === "TR-16") {
    return null;
  }
  const hit = specPromiseCache.get(provinceCode);
  if (hit) return hit;

  const pending = importProvinceSpecRaw(provinceCode).then((spec) => {
    if (!spec) {
      throw new Error(\`[ProvinceRegistry] Failed to load spec for \${provinceCode}\`);
    }
    if (spec.provinceCode !== provinceCode) {
      throw new Error(
        \`[ProvinceRegistry] Province code mismatch: requested \${provinceCode}, got \${spec.provinceCode}\`
      );
    }
    return Object.freeze(spec);
  });

  specPromiseCache.set(provinceCode, pending);
  pending.catch(() => {
    specPromiseCache.delete(provinceCode);
  });
  return pending;
}

/**
 * Lazily loads the calibrated EMOS / donor-simplex bundle for a non-Bursa Turkish province.
 */
export async function loadProvinceCalibration(
  provinceCode: ProvinceCode | string | null | undefined
): Promise<ProvinceCalibrationBundle | null> {
  if (!isTrProvinceCode(provinceCode) || provinceCode === "TR-16") {
    return null;
  }
  return loadProvinceCalibrationBundle(provinceCode);
}

/**
 * Maps a Turkish province to the closest physical Cumulus 3D/2D atmospheric stage preset
 * without bloating client bundles.
 */
export function resolveCumulusStageForProvince(
  provinceCode: TrProvinceCode,
  climateRegion: ClimateRegionKey
): ProvinceClientSummary["cumulusStageId"] {
  if (provinceCode === "TR-34" || provinceCode === "TR-17") {
    return "bogaz";
  }
  if (provinceCode === "TR-16") {
    return "marmara";
  }
  switch (climateRegion) {
    case "MARMARA":
      return "marmara";
    case "EGE":
      return "ege";
    case "AKDENIZ":
      return "akdeniz";
    case "KARADENIZ":
      // Steep coastal Black Sea provinces share maritime-orographic cloud base dynamics
      if (
        provinceCode === "TR-53" ||
        provinceCode === "TR-61" ||
        provinceCode === "TR-08" ||
        provinceCode === "TR-28" ||
        provinceCode === "TR-52" ||
        provinceCode === "TR-55" ||
        provinceCode === "TR-57" ||
        provinceCode === "TR-37" ||
        provinceCode === "TR-74" ||
        provinceCode === "TR-67"
      ) {
        return "marmara";
      }
      return "anadolu";
    case "IC_ANADOLU":
    case "DOGU_ANADOLU":
    case "GUNEYDOGU":
    default:
      return "anadolu";
  }
}

/**
 * Builds the lightweight client-safe summary payload (< 1.2 KB JSON) shipped inside \`WeatherBundle.provinceSummary\`.
 */
export function buildProvinceClientSummary(
  spec: ProvinceSpec,
  opts?: {
    mgmMeshStationCount?: number;
    liveWaterTempsByBodyId?: Readonly<Record<string, number | null | undefined>>;
  }
): ProvinceClientSummary {
  const stationLabel = spec.primaryCenter.wmoId
    ? \`\${spec.nameTr} Merkez (WMO \${spec.primaryCenter.wmoId})\`
    : \`\${spec.nameTr} Merkez (MGM #\${spec.primaryCenter.mgmIstNo})\`;

  return {
    provinceCode: spec.provinceCode,
    plateNumber: spec.plateCode,
    provinceName: spec.nameTr,
    climateRegion: spec.climateRegion,
    calibrationTier: spec.calibrationTier,
    canonicalCenter: {
      id: \`tr-\${String(spec.plateCode).padStart(2, "0")}-\${spec.slug}-merkez\`,
      name: spec.nameTr,
      stationLabel,
      lat: spec.primaryCenter.lat,
      lon: spec.primaryCenter.lon,
      elevationM: spec.primaryCenter.demVerifiedElevationM
    },
    mgmMeshStationCount:
      opts?.mgmMeshStationCount ?? Math.max(1, Object.keys(spec.stationOverrides).length),
    activeWaterBodies: spec.waterBodies.map((wb) => ({
      id: wb.id,
      labelTr: wb.labelTr,
      kind: wb.kind,
      liveTempC: opts?.liveWaterTempsByBodyId?.[wb.id] ?? null,
      upperHpa: wb.convectiveInstabilityUpperHpa
    })),
    cumulusStageId: resolveCumulusStageForProvince(spec.provinceCode, spec.climateRegion),
    curatedSubLocations: spec.curatedSubLocations
  };
}

export const NON_BURSA_PROVINCE_CODES: readonly TrProvinceCode[] = Object.freeze([
${nonBursaPlates.map((p) => `  "TR-${p}"`).join(",\n")}
]);
`;

fs.writeFileSync(targetFile, content, "utf-8");
console.log(`[ORCH-00] Generated ${targetFile} covering ${nonBursaPlates.length} non-Bursa provinces.`);
